"""The Cellucid citation is written once and generated everywhere else.

The preferred-citation block of CITATION.cff is copied from the single source in
theislab/cellucid by ``cellucid-private/scripts/sync_citation.py``, which also
generates the README's citation. The README region records the SHA-256 of the
block it came from and of its own body, so a block changed without re-running
the script, or a region edited by hand, fails here.
"""

from __future__ import annotations

import hashlib
import pathlib
import re
import unittest

REPOSITORY_ROOT = pathlib.Path(__file__).resolve().parents[1]
BLOCK_BEGIN = "# BEGIN cellucid preferred-citation"
BLOCK_END = "# END cellucid preferred-citation"
REGION_BEGIN = re.compile(
    r"(?m)^<!-- BEGIN cellucid-citation \(generated by "
    r"cellucid-private/scripts/sync_citation\.py from CITATION\.cff; do not edit\) "
    r"source-sha256=([0-9a-f]{64}) body-sha256=([0-9a-f]{64}) -->\n"
)
REGION_END = "<!-- END cellucid-citation -->\n"


def _sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _read(name: str) -> str:
    return (REPOSITORY_ROOT / name).read_bytes().decode("utf-8")


class CitationContractTests(unittest.TestCase):
    def _block(self) -> str:
        lines = _read("CITATION.cff").splitlines(keepends=True)
        begins = [i for i, line in enumerate(lines) if line.rstrip("\n") == BLOCK_BEGIN]
        ends = [i for i, line in enumerate(lines) if line.rstrip("\n") == BLOCK_END]
        self.assertEqual(len(begins), 1)
        self.assertEqual(len(ends), 1)
        self.assertGreater(ends[0], begins[0])
        block = "".join(lines[begins[0] : ends[0] + 1])
        return block if block.endswith("\n") else block + "\n"

    def test_readme_citation_is_generated_from_citation_cff_and_unedited(self) -> None:
        readme = _read("README.md")
        begins = list(REGION_BEGIN.finditer(readme))
        self.assertEqual(len(begins), 1, "README.md must hold one generated citation region")
        self.assertEqual(readme.count(REGION_END), 1, "README.md must hold one region end")
        body = readme[begins[0].end() : readme.index(REGION_END)]
        block = self._block()
        self.assertEqual(
            begins[0].group(1),
            _sha256(block),
            "CITATION.cff changed after the README citation was generated; "
            "run cellucid-private/scripts/sync_citation.py",
        )
        self.assertEqual(
            begins[0].group(2),
            _sha256(body),
            "the README citation region was edited by hand; edit "
            "theislab/cellucid/CITATION.cff and run cellucid-private/scripts/sync_citation.py",
        )
        placeholder = re.search(r"(?m)^  doi:", block) is None
        self.assertEqual("**Placeholder citation.**" in body, placeholder)


if __name__ == "__main__":
    unittest.main()
